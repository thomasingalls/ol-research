"""Generate crates/ol-rht/src/macrolanguages.rs from SIL's ISO 639-3
macrolanguage mappings.

    python3 tools/gen_macrolanguages.py [iso-639-3-macrolanguages.tab]

Without an argument it reads
https://iso639-3.sil.org/sites/iso639-3/files/downloads/iso-639-3-macrolanguages.tab
(the ISO 639-3 Registration Authority). A detector names individual
languages (GlotLID's `cmn`), PubMed's indexers macrolanguages (`chi`, which
is `zho`); scoring one against the other folds the first into the second.
"""

import datetime
import sys
import urllib.request

SIL = "https://iso639-3.sil.org/sites/iso639-3/files/downloads/iso-639-3-macrolanguages.tab"


def read(path_or_url):
    if path_or_url.startswith("https://"):
        return urllib.request.urlopen(path_or_url).read().decode("utf-8")
    return open(path_or_url, encoding="utf-8").read()


text = read(sys.argv[1] if len(sys.argv) > 1 else SIL)
pairs = {}
for n, line in enumerate(text.splitlines()):
    if n == 0 or not line.strip():
        continue
    macro, individual, _status = line.split("\t")
    if individual in pairs and pairs[individual] != macro:
        sys.exit(f"{individual} is in both {pairs[individual]} and {macro}")
    pairs[individual] = macro

out = [
    "//! ISO 639-3's macrolanguages: each individual language and the",
    "//! macrolanguage it belongs to. Generated by `tools/gen_macrolanguages.py`",
    f"//! on {datetime.date.today().isoformat()} from SIL International's macrolanguage mappings",
    "//! (<https://iso639-3.sil.org>, the ISO 639-3 Registration Authority).",
    "//! Do not edit by hand.",
    "",
    "/// `(individual, macrolanguage)`, sorted by the individual language.",
    "#[rustfmt::skip]",
    f"pub(crate) static MACROLANGUAGES: [(&str, &str); {len(pairs)}] = [",
]
for individual in sorted(pairs):
    out.append(f'    ("{individual}", "{pairs[individual]}"),')
out.append("];")
out.append("")
open("crates/ol-rht/src/macrolanguages.rs", "w", encoding="utf-8").write("\n".join(out))
print(f"{len(pairs)} individual languages")
