#!/usr/bin/env python3
"""Regenerates crates/model/src/lang/table.rs from Debian's iso-codes data.

    python3 tools/gen_lang_table.py [path/to/iso_639-2.json]

Without a path, fetches
https://salsa.debian.org/iso-codes-team/iso-codes/-/raw/main/data/iso_639-2.json
"""
import datetime, json, sys, urllib.request

URL = "https://salsa.debian.org/iso-codes-team/iso-codes/-/raw/main/data/iso_639-2.json"
if len(sys.argv) > 1:
    data = json.load(open(sys.argv[1], encoding="utf-8"))
else:
    data = json.load(urllib.request.urlopen(URL))
entries = []
for e in data["639-2"]:
    code = e["alpha_3"]
    if code == "qaa-qtz":  # the reserved range, not a code
        continue
    assert len(code) == 3 and code.isascii() and code.isalpha() and code.islower(), code
    for k in ("bibliographic", "alpha_2"):
        v = e.get(k)
        if v is not None:
            assert v.isascii() and v.isalpha() and v.islower(), (code, k, v)
    entries.append((code, e.get("bibliographic"), e.get("alpha_2"), e["name"]))
entries.sort()
assert len({c for c, *_ in entries}) == len(entries)
bib = sorted((b, i) for i, (_, b, _, _) in enumerate(entries) if b)
a2 = sorted((a, i) for i, (_, _, a, _) in enumerate(entries) if a)
assert len({b for b, _ in bib}) == len(bib) and len({a for a, _ in a2}) == len(a2)
opt = lambda v: f'Some("{v}")' if v else "None"
esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
out = [
    "//! ISO 639-2 language codes. Generated by `tools/gen_lang_table.py` on",
    f"//! {datetime.date.today().isoformat()} from Debian's iso-codes data",
    "//! (<https://salsa.debian.org/iso-codes-team/iso-codes>, data under LGPL-2.1+);",
    "//! the codes and names themselves are the ISO 639-2 registry, maintained by",
    "//! the Library of Congress. Do not edit by hand.",
    "",
    "/// One language: the terminologic alpha-3 code (the canonical form here),",
    "/// the bibliographic alpha-3 code where ISO defines a different one, the",
    "/// alpha-2 code where one exists, and the English name.",
    "pub(super) struct Entry {",
    "    pub(super) alpha_3: &'static str,",
    "    pub(super) bibliographic: Option<&'static str>,",
    "    pub(super) alpha_2: Option<&'static str>,",
    "    pub(super) name: &'static str,",
    "}",
    "",
    "/// Sorted by `alpha_3`.",
    f"pub(super) static ENTRIES: [Entry; {len(entries)}] = [",
]
for code, b, a, name in entries:
    out.append(f'    Entry {{ alpha_3: "{code}", bibliographic: {opt(b)}, alpha_2: {opt(a)}, name: "{esc(name)}" }},')
out += ["];", "", "/// Bibliographic codes that differ from the terminologic one, sorted, with", "/// the index into [`ENTRIES`].", f"pub(super) const BIBLIOGRAPHIC: [(&str, u16); {len(bib)}] = ["]
out += [f'    ("{b}", {i}),' for b, i in bib]
out += ["];", "", "/// Alpha-2 codes, sorted, with the index into [`ENTRIES`].", f"pub(super) const ALPHA_2: [(&str, u16); {len(a2)}] = ["]
out += [f'    ("{a}", {i}),' for a, i in a2]
out += ["];", ""]
open("crates/model/src/lang/table.rs", "w", encoding="utf-8").write("\n".join(out))
print(f"wrote {len(entries)} entries, {len(bib)} bibliographic, {len(a2)} alpha-2")
