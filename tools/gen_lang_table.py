#!/usr/bin/env python3
"""Regenerates crates/model/src/lang/table.rs from ISO 639-3 and ISO 639-2.

    python3 tools/gen_lang_table.py [iso-639-3.tab [iso_639-2.json]]

ISO 639-3's individual languages, from SIL International's code table (the
ISO 639-3 Registration Authority), and ISO 639-2's codes from Debian's
iso-codes data, which bring the group codes 639-3 leaves out (`afa`,
Afro-Asiatic languages) and mark which codes are 639-2's, since PubMed
writes 639-2's bibliographic codes and no others. Where both give a code,
they must agree on its bibliographic and alpha-2 forms, or this stops.

Without paths, fetches
https://iso639-3.sil.org/sites/iso639-3/files/downloads/iso-639-3.tab and
https://salsa.debian.org/iso-codes-team/iso-codes/-/raw/main/data/iso_639-2.json
"""
import csv, datetime, io, json, sys, unicodedata, urllib.request

SIL = "https://iso639-3.sil.org/sites/iso639-3/files/downloads/iso-639-3.tab"
DEBIAN = "https://salsa.debian.org/iso-codes-team/iso-codes/-/raw/main/data/iso_639-2.json"


def read(path_or_url):
    if path_or_url.startswith("https://"):
        return urllib.request.urlopen(path_or_url).read().decode("utf-8")
    return open(path_or_url, encoding="utf-8").read()


sil = read(sys.argv[1] if len(sys.argv) > 1 else SIL)
debian = json.loads(read(sys.argv[2] if len(sys.argv) > 2 else DEBIAN))

part2 = {}
for e in debian["639-2"]:
    code = e["alpha_3"]
    if code == "qaa-qtz":  # the reserved range, not a code
        continue
    part2[code] = (e.get("bibliographic"), e.get("alpha_2"), e["name"])

entries = {}
for r in csv.DictReader(io.StringIO(sil), delimiter="\t"):
    code = r["Id"]
    bib = r["Part2b"] if r["Part2b"] and r["Part2b"] != code else None
    a2 = r["Part1"] or None
    if code in part2:
        b2, a22, name = part2[code]
        assert (b2, a22) == (bib, a2), (code, (b2, a22), (bib, a2))
    else:
        name = r["Ref_Name"]
    entries[code] = (bib, a2, name, code in part2)
for code, (bib, a2, name) in part2.items():
    if code not in entries:
        entries[code] = (bib, a2, name, True)

for code, (bib, a2, _, _) in entries.items():
    assert len(code) == 3 and code.isascii() and code.isalpha() and code.islower(), code
    for v in (bib, a2):
        assert v is None or (v.isascii() and v.isalpha() and v.islower()), (code, v)
items = sorted(entries.items())
assert len(items) < 1 << 16
bib = sorted((b, i) for i, (_, (b, _, _, _)) in enumerate(items) if b)
a2 = sorted((a, i) for i, (_, (_, a, _, _)) in enumerate(items) if a)
assert len({b for b, _ in bib}) == len(bib) and len({a for a, _ in a2}) == len(a2)
opt = lambda v: f'Some("{v}")' if v else "None"
esc = lambda s: unicodedata.normalize("NFC", s).replace("\\", "\\\\").replace('"', '\\"')
out = [
    "//! ISO 639-3 and ISO 639-2 language codes. Generated by",
    f"//! `tools/gen_lang_table.py` on {datetime.date.today().isoformat()} from SIL International's",
    "//! ISO 639-3 code table (<https://iso639-3.sil.org>, the ISO 639-3",
    "//! Registration Authority) and Debian's iso-codes data for ISO 639-2",
    "//! (<https://salsa.debian.org/iso-codes-team/iso-codes>, data under",
    "//! LGPL-2.1+; the registry is the Library of Congress's). A code in both",
    "//! takes ISO 639-2's name. Do not edit by hand.",
    "",
    "/// One language: the terminologic alpha-3 code (the canonical form here),",
    "/// the bibliographic alpha-3 code where ISO defines a different one, the",
    "/// alpha-2 code where one exists, the English name, and whether ISO 639-2",
    "/// has it — ISO 639-3's individual languages outnumber it sixteenfold.",
    "pub(super) struct Entry {",
    "    pub(super) alpha_3: &'static str,",
    "    pub(super) bibliographic: Option<&'static str>,",
    "    pub(super) alpha_2: Option<&'static str>,",
    "    pub(super) name: &'static str,",
    "    pub(super) part2: bool,",
    "}",
    "",
    "/// Sorted by `alpha_3`. One line a language, as generated.",
    "#[rustfmt::skip]",
    f"pub(super) static ENTRIES: [Entry; {len(items)}] = [",
]
for code, (b, a, name, p2) in items:
    out.append(
        f'    Entry {{ alpha_3: "{code}", bibliographic: {opt(b)}, alpha_2: {opt(a)}, '
        f'name: "{esc(name)}", part2: {str(p2).lower()} }},'
    )
out += ["];", "", "/// Bibliographic codes that differ from the terminologic one, sorted, with", "/// the index into [`ENTRIES`].", f"pub(super) const BIBLIOGRAPHIC: [(&str, u16); {len(bib)}] = ["]
out += [f'    ("{b}", {i}),' for b, i in bib]
out += ["];", "", "/// Alpha-2 codes, sorted, with the index into [`ENTRIES`].", f"pub(super) const ALPHA_2: [(&str, u16); {len(a2)}] = ["]
out += [f'    ("{a}", {i}),' for a, i in a2]
out += ["];", ""]
open("crates/model/src/lang/table.rs", "w", encoding="utf-8").write("\n".join(out))
print(f"wrote {len(items)} entries ({sum(1 for _, e in items if e[3])} in ISO 639-2), {len(bib)} bibliographic, {len(a2)} alpha-2")
